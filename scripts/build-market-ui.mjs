import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { calculateMarket } from '../src/market-sizing.ts';
const font = readFileSync('public/assets/fonts/Archivo-latin-1.woff2').toString('base64');
const template = readFileSync('src/market-sizing-ui.html', 'utf8');
const html = template.replace('/*CALCULATE*/', calculateMarket.toString()).replace('FONT_DATA', font);
mkdirSync('public/lab/market-sizing', { recursive: true });
writeFileSync('public/lab/market-sizing/index.html', html);
writeFileSync('src/market-sizing-ui.ts', '// Generated by node scripts/build-market-ui.mjs. Do not edit.\nexport const marketSizingHtml = ' + JSON.stringify(html) + ';\n');
