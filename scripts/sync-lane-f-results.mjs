// Regenerates src/lane-f-results-html.ts from the reviewed Lane F widget build.
// Usage: node scripts/sync-lane-f-results.mjs <gtmhelix-tools-hub checkout>/lane-f/widgets/dist/results.html
// The file must be byte identical to the reviewed build (sha256 below); any other file is refused.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
export const RESULTS_SHA256 = 'a8492c128f5bbff68cdbd2c824d46335aec70b4379ad787c2ad35f30dc581a02';
const source = process.argv[2];
if (!source) throw new Error('Supply the path to lane-f/widgets/dist/results.html');
const html = readFileSync(source, 'utf8');
const digest = createHash('sha256').update(html, 'utf8').digest('hex');
if (digest !== RESULTS_SHA256) throw new Error(`results.html sha256 ${digest} differs from the reviewed build ${RESULTS_SHA256}`);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
writeFileSync(path.join(root, 'src/lane-f-results-html.ts'),
  `// Generated by scripts/sync-lane-f-results.mjs from gtmhelix-tools-hub commit b020fd20c20837545309edb537ff6d904ee5d06c,\n` +
  `// lane-f/widgets/dist/results.html (sha256 ${RESULTS_SHA256}). Do not edit.\n` +
  `export const LANE_F_RESULTS_HTML = ${JSON.stringify(html)};\n`);
console.log('Wrote src/lane-f-results-html.ts from', digest);
